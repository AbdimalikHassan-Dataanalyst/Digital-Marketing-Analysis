# HEADLINE CLEANING

import pandas as pd
import numpy as np

df = pd.read_csv('marketing_campaign_data_messy.csv')
print(df.head(30))

# headlines

print(df.columns.tolist())

df.columns = df.columns.str.lower().str.strip().str.replace(' ','_')

print('fixid applied')
print(df.columns.tolist())

# currence
dirty_spend_mask = df['spend'].astype(str).str.contains(r'\$')
print(df.loc[dirty_spend_mask,['campaign_id','spend']].head(10))

df['spend'] = df['spend'].astype(str).str.replace(r'[^\d.-]', '', regex=True)
df['spend'] = pd.to_numeric(df['spend'],errors = 'coerce')


print('fixid applied')
print(df.loc[dirty_spend_mask,['campaign_id','spend']].head(10))

# date parsing

print(df['start_date'].dtype)


df['start_date'] = pd.to_datetime(df['start_date'],errors = 'coerce')
df['end_date'] = pd.to_datetime(df['end_date'],errors = 'coerce')
print('fixid applied')
print(df['start_date'].dtype)

# category conversion


print(df['channel'].unique())

cleanup_map = {
    'Tik_Tok' : 'TikTok',
    'Facebok' : 'Facebook',
    'Insta_gram' : 'Instagram',
    'E-mail' : 'Email',
    'Google' : 'Google Ads',
    'N/A' : 'Unknown'
}

df['channel'] = df['channel'].replace(cleanup_map)

print('fixid applied')
print(df['channel'].unique())

# boolean masking


print(df['active'].unique())

bool_mask = {
    'Y' : True,
    '0' : False,
    'No' : False,
    'True' : True,
    'Yes' : True,
    '1' :True,
    'False' : False
}

df['active'] = df['active'].replace(bool_mask)

print('fixid applied')

print(df['active'].unique())

# time travel

time_travel_mask = df['end_date'] < df['start_date']

print(df.loc[time_travel_mask,['campaign_id','start_date','end_date']].head(3))

df.loc[time_travel_mask,'end_date'] = df.loc[time_travel_mask,'start_date'] + pd.Timedelta(days=30)

print('fixid applied')

print(df.loc[time_travel_mask,['campaign_id','start_date','end_date']].head(3))

from numpy._core.defchararray import upper
# outlire mask

Q1 = df['spend'].quantile(0.25)
Q3 = df['spend'].quantile(0.75)

IQR = Q3 - Q1
upper_limit = Q3 + (3 * IQR)

outlier_mask = df['spend'] > upper_limit
print(df.loc[outlier_mask,['campaign_id','spend']].head(3))

print("FIX APPLIED")
df.loc[outlier_mask, 'spend'] = upper_limit
print(df.loc[outlier_mask,['campaign_id','spend']].head(3))



# feature extract

print(df['campaign_name'].head(4))

df['season'] = df['campaign_name'].str.extract(r'Q\d_([^_]+)')

print('fixid applied')
print(df['season'].head(4))

df.iloc[:, ~df.columns.duplicated()]

